def _registry(source: type) -> dict[str, str]:
    return {
        str(value).replace("-", "").upper(): name
        for name, value in vars(source).items()
        if not name.startswith("_") and isinstance(value, str)
    }


MODULE_ID_TO_NAME = _registry(ModuleConstants)
FILTER_VIEW_ID_TO_NAME = _registry(ModuleFilter2FormViewConstants)


def normalize_module_id(value: object) -> str:
    """Return a canonical lowercase UUID or an empty string for invalid input."""
    try:
        return str(UUID(str(value or "").strip())).lower()
    except (ValueError, TypeError, AttributeError):
        return ""


def resolve_record_module(value: object) -> dict[str, str]:
    """Resolve a payload module id without trusting arbitrary display labels."""
    normalized = normalize_module_id(value)
    key = normalized.replace("-", "").upper() if normalized else ""
    return {
        "idRecordModule": normalized,
        "moduleName": MODULE_ID_TO_NAME.get(key, ""),
        "known": "true" if key in MODULE_ID_TO_NAME else "false",
    }

